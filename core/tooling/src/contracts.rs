use marketplace_artifacts::{file_identity, invalid, parse_json, read_file};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

const DEFINITIONS: [&str; 2] = ["contracts.schema.json", "openapi.json"];
const GENERATED_TS: &str = "contracts/v1/http-operations.generated.ts";
const GENERATED_RUST: &str = "core/app-contracts/src/http/operations.rs";

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Registry {
    limits: Limits,
    operations: Vec<Value>,
}

#[derive(Deserialize, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Limits {
    max_json_bytes: u64,
    max_json_depth: usize,
    max_list_entries: u64,
    default_deadline_ms: u64,
    max_deadline_ms: u64,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Operation {
    socket: String,
    method: String,
    path: String,
    path_parameter: Option<String>,
    #[serde(default)]
    idempotency_key: bool,
    #[serde(default)]
    resume_cursor: bool,
    request: Option<String>,
    response: Option<String>,
    event: Option<String>,
    status: u16,
    summary: String,
    description: Option<String>,
    failures: Option<BTreeMap<u16, String>>,
}

fn quote(value: &str) -> String {
    serde_json::to_string(value).expect("serialize publisher string")
}

fn optional(value: Option<&str>) -> String {
    value.map_or_else(
        || "None".to_owned(),
        |value| format!("Some({})", quote(value)),
    )
}

fn identity(value: &str) -> bool {
    value.as_bytes().split_first().is_some_and(|(first, rest)| {
        first.is_ascii_lowercase() && rest.iter().all(u8::is_ascii_alphanumeric)
    })
}

fn pretty(value: &impl Serialize) -> String {
    let mut output = Vec::new();
    let formatter = serde_json::ser::PrettyFormatter::with_indent(b"    ");
    let mut serializer = serde_json::Serializer::with_formatter(&mut output, formatter);
    value
        .serialize(&mut serializer)
        .expect("serialize generated registry");
    String::from_utf8(output).expect("JSON is UTF-8")
}

fn generate(bytes: &[u8]) -> io::Result<(String, String)> {
    let data: Registry = serde_json::from_value(parse_json(bytes)?)?;
    let depth = data.limits.max_json_depth;
    if !(1..=128).contains(&depth)
        || data.limits.max_json_bytes == 0
        || data.limits.max_list_entries == 0
        || data.limits.default_deadline_ms == 0
        || data.limits.default_deadline_ms > data.limits.max_deadline_ms
    {
        return Err(invalid("Invalid HTTP registry limits"));
    }
    let mut seen = BTreeSet::new();
    let mut operations = Vec::new();
    let mut ts_entries = String::from("{\n");
    for mut raw in data.operations {
        let id = raw
            .as_object_mut()
            .and_then(|operation| operation.remove("id"))
            .and_then(|id| id.as_str().map(str::to_owned))
            .filter(|id| identity(id) && seen.insert(id.clone()))
            .ok_or_else(|| invalid("Invalid or duplicate HTTP operation id"))?;
        let operation: Operation = serde_json::from_value(raw.clone())?;
        if !matches!(operation.status, 200 | 202 | 204)
            || !operation.path.starts_with('/')
            || operation.summary.is_empty()
            || operation.description.as_deref().is_some_and(str::is_empty)
            || operation.failures.as_ref().is_some_and(|failures| {
                failures
                    .iter()
                    .any(|(status, message)| !(400..=599).contains(status) || message.is_empty())
            })
        {
            return Err(invalid("Invalid HTTP operation descriptor"));
        }
        let mut variant = id.clone();
        variant[..1].make_ascii_uppercase();
        writeln!(
            ts_entries,
            "    {id}: {},",
            pretty(&raw).replace('\n', "\n    ")
        )
        .unwrap();
        operations.push((id, variant, operation));
    }
    if operations.is_empty() {
        return Err(invalid("Missing HTTP operation descriptors"));
    }
    let ts = format!(
        "// Generated by bun run contracts:generate.\n\nexport const generatedRpcLimits = {} as const\n\nexport const generatedHttpOperations = {} as const\n",
        pretty(&data.limits),
        ts_entries + "}",
    );
    let mut rust = format!(
        "// Generated by bun run contracts:generate.\n\nuse super::{{HttpDescriptor, HttpMethod, HttpSocket}};\n\npub const MAX_JSON_DEPTH: usize = {depth};\n\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub enum HttpOperation {{\n"
    );
    for (_, variant, _) in &operations {
        writeln!(rust, "    {variant},").unwrap();
    }
    rust.push_str("}\n\nimpl HttpOperation {\n    pub fn from_id(id: &str) -> Option<Self> {\n        match id {\n");
    for (id, variant, _) in &operations {
        writeln!(rust, "            \"{id}\" => Some(Self::{variant}),").unwrap();
    }
    rust.push_str("            _ => None,\n        }\n    }\n\n    pub fn id(self) -> &'static str {\n        match self {\n");
    for (id, variant, _) in &operations {
        writeln!(rust, "            Self::{variant} => \"{id}\",").unwrap();
    }
    rust.push_str("        }\n    }\n\n    pub fn descriptor(self) -> HttpDescriptor {\n        match self {\n");
    for (_, variant, op) in operations {
        let method = match op.method.as_str() {
            "GET" => "Get",
            "POST" => "Post",
            _ => return Err(invalid("Unknown HTTP operation method")),
        };
        let socket = match op.socket.as_str() {
            "app.sock" => "App",
            "core.sock" => "Core",
            _ => return Err(invalid("Unknown HTTP operation socket")),
        };
        writeln!(rust,
            "            Self::{variant} => HttpDescriptor {{\n                method: HttpMethod::{method},\n                socket: HttpSocket::{socket},\n                path: {},\n                path_parameter: {},\n                idempotency_key: {},\n                resume_cursor: {},\n                request: {},\n                success_status: {},\n                response: {},\n                event: {},\n            }},",
            quote(&op.path), optional(op.path_parameter.as_deref()), op.idempotency_key,
            op.resume_cursor, optional(op.request.as_deref()), op.status,
            optional(op.response.as_deref()), optional(op.event.as_deref()),
        ).unwrap();
    }
    rust.push_str("        }\n    }\n}\n");
    Ok((ts, rust))
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Sync {
    root: PathBuf,
    check: bool,
    documents: BTreeMap<String, String>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct SyncRegistry {
    root: PathBuf,
    check: bool,
}

fn sync_file(root: &Path, name: &str, content: &str, check: bool) -> io::Result<()> {
    let path = root.join(name);
    if check {
        let existing = std::fs::read_to_string(path)?;
        if existing.replace("\r\n", "\n") != content {
            return Err(invalid(format!(
                "{name} is out of date. Run bun run contracts:generate."
            )));
        }
    } else {
        let parent = path
            .parent()
            .ok_or_else(|| invalid("Missing generated file parent"))?;
        let mut staged = tempfile::NamedTempFile::new_in(parent)?;
        staged.write_all(content.as_bytes())?;
        staged.persist(path).map_err(|error| error.error)?;
    }
    Ok(())
}

fn sync(input: Sync) -> io::Result<Value> {
    if input.documents.len() != DEFINITIONS.len() {
        return Err(invalid("Unexpected contract document set"));
    }
    for name in DEFINITIONS {
        let document = input
            .documents
            .get(name)
            .ok_or_else(|| invalid("Missing contract document"))?;
        if !parse_json(document.as_bytes())?.is_object() {
            return Err(invalid("Invalid contract document"));
        }
        sync_file(
            &input.root,
            &format!("contracts/v1/{name}"),
            document,
            input.check,
        )?;
    }
    Ok(Value::Null)
}

fn sync_registry(input: SyncRegistry) -> io::Result<Value> {
    let registry = read_file(
        &input.root.join("contracts/v1/http-operations.json"),
        512 * 1024,
    )?;
    let (types, rust) = generate(&registry)?;
    sync_file(&input.root, GENERATED_TS, &types, input.check)?;
    sync_file(&input.root, GENERATED_RUST, &rust, input.check)?;
    Ok(Value::Null)
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Bundle {
    directory: PathBuf,
    version: String,
    source_commit: String,
}

fn bundle(input: Bundle) -> io::Result<Value> {
    if input.source_commit.len() != 40
        || !input
            .source_commit
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
        || input.version.len() > 48
        || !input.version.starts_with(|c: char| c.is_ascii_digit())
        || !input
            .version
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b".-+".contains(&byte))
    {
        return Err(invalid("Invalid contract bundle identity"));
    }
    let versions = [
        "LICENSE".to_owned(),
        "contracts.schema.json".to_owned(),
        "openapi.json".to_owned(),
        format!("rentnerproxy-app-contracts-{}.tgz", input.version),
        format!("rentnerproxy-app-contracts-{}.crate", input.version),
    ];
    let mut sha256 = BTreeMap::new();
    for file in versions {
        let identity = file_identity(&input.directory.join(&file), 16 * 1024 * 1024)?;
        if identity.size_bytes == 0 {
            return Err(invalid("Empty contract bundle member"));
        }
        sha256.insert(file, identity.sha256);
    }
    Ok(json!({
        "version": input.version,
        "sourceCommit": input.source_commit,
        "packages": { "npm": "@rentnerproxy/app-contracts", "cargo": "rentnerproxy-app-contracts" },
        "sha256": sha256,
    }))
}

pub fn execute(operation: &str, input: Value) -> io::Result<Value> {
    match operation {
        "registry" => sync_registry(serde_json::from_value(input)?),
        "sync" => sync(serde_json::from_value(input)?),
        "bundle" => bundle(serde_json::from_value(input)?),
        _ => Err(invalid("Unknown contracts tooling operation")),
    }
}
